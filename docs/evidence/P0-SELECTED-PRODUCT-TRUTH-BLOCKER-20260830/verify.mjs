import fs from "node:fs";
import assert from "node:assert/strict";
const root=new URL("./",import.meta.url);
const read=(name)=>JSON.parse(fs.readFileSync(new URL(name,root),"utf8"));
const summary=read("SUMMARY.json"),provenance=read("PROVENANCE-RECEIPT.json"),attempts=read("BLOCKED-ATTEMPTS.json"),candidates=read("PRINCIPAL-CANDIDATES.json"),zero=read("ZERO-MUTATION.json");
