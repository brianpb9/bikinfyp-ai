const exactSha="ee767201679ae2213c40be6f913241f372d2378a";
assert.equal(summary.selected_product_id,productId);
assert.equal(summary.result,"FOUNDER_DECISION_REQUIRED");
assert.equal(provenance.exact_sha,exactSha);
assert.equal(provenance.product.id,productId);
assert.equal(provenance.references.length,1);
assert.equal(provenance.references[0].bytes_present,true);
assert.equal(provenance.references[0].bytes_sha256,"9f0ec3417cf6121c018dd5da86f38b402fac8fd40bf0a712429de8586ca081ef");
assert.equal(provenance.references[0].sidecar_present,false);
assert.equal(provenance.product.source_host,null);
assert.deepEqual(provenance.product.raw_meta_safe,{});
assert.equal(provenance.authorization_conclusion,"UNCONFIRMED");
assert.equal(attempts.exact_sha,exactSha);
assert.deepEqual(attempts.attempts.map(x=>x.error),["FOUNDER_ROLE_NOT_CONFIGURED","OWNER_AUTH_IDENTITY_REQUIRED"]);
assert.ok(attempts.attempts.every(x=>x.status==="failed"&&x.write_started===false));
assert.equal(candidates.exact_sha,exactSha);
assert.equal(candidates.configured_role,null);
assert.equal(candidates.configured_principal_id,null);
assert.equal(candidates.selected_product_owner_id,"7c6fbc1f-bc21-493f-8405-158c4255fe15");
const owner=candidates.candidates.find(x=>x.principal_id===candidates.selected_product_owner_id);
assert.equal(owner.masked_email,null);
assert.equal(owner.has_normal_email_otp_path,false);
assert.equal(candidates.candidate_count,candidates.candidates.length);
assert.ok(candidates.candidates.every(x=>!x.masked_email||/^.\*\*\*@/.test(x.masked_email)));
